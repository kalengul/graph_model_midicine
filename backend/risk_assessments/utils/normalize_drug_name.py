"""
Утилиты нормализации строк для поиска препаратов и противопоказаний в БД.
"""
import re


def normalize_drug_name(name: str) -> str:
    """
    Нормализует название препарата для поиска:
      - приводит к нижнему регистру
      - заменяет разделители (';', '/', '+') на '+'
      - удаляет лишние пробелы

    Примеры:
      "Амлодипин + Периндоприл" -> "амлодипин+периндоприл"
      "Амлодипин/Периндоприл"   -> "амлодипин+периндоприл"
      "  Варфарин  "            -> "варфарин"
      "   Ацетилсалицилловая  кислота" -> "ацетилсалицилловая кислота"
      " Железа   (III) гидроксид полимальтозат   " -> "железа (iii) гидроксид полимальтозат"
    """
    result = name.lower()
    split_symbols = [';', '/', '+']
    
    for symbol in split_symbols:
        # Экранируем символ, если он специальный для regex
        escaped_symbol = re.escape(symbol)
        result = re.sub(r'\s*' + escaped_symbol + r'\s*', '+', result)
    
    # Удаляем лишние пробелы (сохраняем одиночные)
    return re.sub(r'\s+', ' ', result).strip()