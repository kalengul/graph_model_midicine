"""
Утилиты нормализации строк для поиска препаратов и противопоказаний в БД.
"""


def normalize_drug_name(name: str) -> str:
    """
    Нормализует название препарата для поиска:
      - приводит к нижнему регистру
      - заменяет '/' на '+'
      - удаляет пробелы

    Примеры:
      "Амлодипин + Периндоприл" -> "амлодипин+периндоприл"
      "Амлодипин/Периндоприл"   -> "амлодипин+периндоприл"
      "  Варфарин  "            -> "варфарин"
    """
    return name.lower().replace("/", "+").replace(" ", "")