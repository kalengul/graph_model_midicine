"""Конфигурация параметров интерпретации ТДШ."""

LAMBDA = 0.85
MAX_PATH_LENGTH = 8

# Тип вершины графа, обозначающий общий механизм действия.
# Используется для кластеризации зависимых путей внутри препарата.
MECHANISM_LABEL = "mechanism"

# Ниже этой байесовской вероятности эффект не показываем вовсе —
# слишком незначим, чтобы тратить на него объяснение.
MIN_TDSH_PROBABILITY = 0.01

# Минимальный прирост вероятности комбинации препаратов над
# максимальной вероятностью любого препарата по отдельности,
# чтобы считать эффект действительно вызванным взаимодействием,
# а не унаследованным от одного препарата без вклада остальных.
# Строго > 0, чтобы отсечь случаи точного (в т.ч. до float) совпадения
# с базовым (одиночным) значением — см. tdsh_target_effects в interpreter.py.
RANK_CHANGE_EPSILON = 1e-9


def k_by_length(length: int) -> float:
    """Коэффициент уверенности k = λ^(length-1)."""
    return LAMBDA ** max(length - 1, 0)
